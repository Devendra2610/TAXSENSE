"""
ITR-5 Document Parser
=====================
Extracts structured financial data from ITR-5.docx (Income Tax Return Form 5)
for LLPs / Firms. Parses Part A-BS (Balance Sheet), Part A-Trading Account,
and Part A-P&L (Profit & Loss) tables.

The ITR-5 docx generated by the IT department portal uses wide merged-cell tables.
Values are found at specific column indices within each table:
  - Part A-BS (Table 7):  sub-items at col14, totals at col16
  - Part A-Trading (Table 9): sub-items at col7, totals at col9
  - Part A-P&L (Table 10): sub-items at col15, totals at col29

This module provides a single entry point: parse_itr5(filepath) which returns
a flat dictionary of extracted amounts keyed by schedule references.
"""

